interface HelpButtonProps {
  /** 단일 용어 키 또는 여러 용어 키 */
  termKey?: keyof typeof SAJU_GLOSSARY;
  termKeys?: (keyof typeof SAJU_GLOSSARY)[];
  size?: number;
  color?: string;
}

export function HelpButton({ termKey, termKeys, size = 18, color = theme.colors.text.tertiary }: HelpButtonProps) {
  const [visible, setVisible] = useState(false);
  const keys = termKeys ?? (termKey ? [termKey] : []);
  const terms = keys.map(k => SAJU_GLOSSARY[k]).filter(Boolean);

  if (terms.length === 0) return null;

  return (
    <>
      <Pressable
        onPress={() => setVisible(true)}
        hitSlop={8}
        style={[styles.btn, { width: size, height: size, borderRadius: size / 2 }]}
      >
        <Text style={[styles.btnText, { fontSize: size * 0.65, color }]}>?</Text>
      </Pressable>

      <Modal
        visible={visible}
        transparent
        animationType="fade"
        onRequestClose={() => setVisible(false)}
      >
        <Pressable style={styles.overlay} onPress={() => setVisible(false)}>
          <Pressable style={styles.modal} onPress={(e) => e.stopPropagation()}>
            <View style={styles.header}>
              <Text style={styles.title}>용어 해설</Text>
              <TouchableOpacity onPress={() => setVisible(false)} hitSlop={12}>
                <Text style={styles.close}>X</Text>
              </TouchableOpacity>
            </View>

            <ScrollView style={styles.scroll} showsVerticalScrollIndicator={false}>
              {terms.map((term, idx) => (
                <View key={idx} style={idx > 0 ? styles.termGap : undefined}>
                  <Text style={styles.termTitle}>{term.title}</Text>
                  <Text style={styles.short}>{term.short}</Text>
                  <Text style={styles.detail}>{term.detail}</Text>
                </View>
              ))}
            </ScrollView>
          </Pressable>
        </Pressable>
      </Modal>
    </>
  );
}

